-- As tabelas da aplicação são relacionais e devem ser criadas pelo
-- Banco_de_dados/schema-relacional.sql.
-- A service role key deve ficar somente no backend, nunca no frontend.
grant usage on schema public to service_role;
grant select, insert, update, delete on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

create table if not exists public.machines (
	id uuid primary key default gen_random_uuid(),
	machine_code text unique,
	name text not null,
	model text,
	type text,
	controller text,
	created_at timestamptz not null default now()
);

create table if not exists public.telemetry_logs (
	id bigint generated by default as identity primary key,
	machine_id uuid not null references public.machines(id) on delete cascade,
	status text,
	"timestamp" timestamptz not null default now(),
	oee numeric not null default 0,
	current_program text,
	part_count bigint not null default 0,
	spindle_load numeric not null default 0,
	feed_rate numeric not null default 0,
	spindle_speed numeric not null default 0,
	wire_tension numeric not null default 0,
	tonnage numeric not null default 0,
	strokes_per_min numeric not null default 0,
	active_alarms jsonb not null default '[]'::jsonb,
	voltage numeric not null default 0,
	"current" numeric not null default 0
);

alter table public.telemetry_logs
	add column if not exists voltage numeric not null default 0,
	add column if not exists "current" numeric not null default 0;

create index if not exists idx_telemetry_logs_machine_timestamp
	on public.telemetry_logs (machine_id, "timestamp" desc);

alter table public.machines enable row level security;
alter table public.telemetry_logs enable row level security;

grant select, insert, update, delete on public.machines, public.telemetry_logs to service_role;
grant usage, select on all sequences in schema public to service_role;

notify pgrst, 'reload schema';